public class Operadores {
    public static void main(String[] args) {
        //operadores

        //aritmeticos
        var a=5;
        var b=3;

        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
        System.out.println(a%b);

        //asignacion
        a = b;
        System.out.println(a);

        a = b*2;
        System.out.println(a);

        a += 1; // a -=1, a *=2, a /=2, a %=2 son otros casos
        System.out.println(a);

        //Comparacion

    }
}
